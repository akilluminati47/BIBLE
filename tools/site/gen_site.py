"""Generated parts of the BIBLE site (site/), made from the real sources so they cannot drift by hand:
  site/js/font5x7.js      BIBLE's splash font, from src/splash_render.c
  site/js/pillars_glsl.js the towers' shaders, from the RIPPS2 site's pillars.js (a sibling checkout, ps2-pillars)
  site/assets/            BIBLE's logo and button sheet, and the RIPPS2 fonts
    python tools/site/gen_site.py   (run from the BIBLE repo)"""
import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SITE = ROOT / 'site'
PILLARS = ROOT.parent / 'ps2-pillars'
FONTS = Path('B:/Videos - Projects/.montages/hyperframes/ripps2-recap/assets/fonts')

src = (ROOT / 'src' / 'splash_render.c').read_text(encoding='utf-8')
glyphs = {}
for m in re.finditer(r"\{'(\\?.)',\s*\{([^}]*)\}\}", src):
    ch = m.group(1)[-1]
    glyphs[ch] = [int(v, 16) for v in m.group(2).replace(' ', '').split(',')]
assert len(glyphs) >= 60 and 'A' in glyphs
(SITE / 'js').mkdir(parents=True, exist_ok=True)
(SITE / 'js' / 'font5x7.js').write_text(
    '// Generated by tools/site/gen_site.py from src/splash_render.c: 5 wide, 7 high, the top row first, bit 4 the left column.\n'
    'export const FONT = ' + json.dumps(glyphs, separators=(',', ':')) + ';\n', encoding='utf-8')

p = (PILLARS / 'pillars.js').read_text(encoding='utf-8')
out = ['// Generated by tools/site/gen_site.py from the RIPPS2 site\'s pillars.js: the towers as the RIPPS2 site and the ELF draw them.']
for name in ('GLSL_COMMON', 'PILLAR_VERT', 'PILLAR_FRAG', 'FLOOR_VERT', 'FLOOR_FRAG', 'MOTE_VERT', 'MOTE_FRAG', 'SKY_VERT', 'SKY_FRAG'):
    m = re.search(r'const %s = /\* glsl \*/ `.*?`;\n' % name, p, re.S)
    assert m, name
    out.append('export ' + m.group(0).rstrip())
(SITE / 'js' / 'pillars_glsl.js').write_text('\n'.join(out) + '\n', encoding='utf-8')

a = SITE / 'assets'
a.mkdir(exist_ok=True)
for f in ('logo_ps2bble.png', 'hotkeys.png'):
    shutil.copyfile(ROOT / 'assets' / 'embedded' / f, a / f)
for f in ('planet-n-compact.ttf', 'ripps2-one.ttf', 'ripps2-sleek-bold.ttf', 'ripps2-sleek-case.ttf'):
    if (FONTS / f).exists():
        shutil.copyfile(FONTS / f, a / f)
for f in ('ripps2-icon.png', 'bible-splash.gif'):
    shutil.copyfile(ROOT / 'assets' / 'readme' / f, a / f)
print(len(glyphs), 'glyphs;', 'shaders', len(out) - 1)
